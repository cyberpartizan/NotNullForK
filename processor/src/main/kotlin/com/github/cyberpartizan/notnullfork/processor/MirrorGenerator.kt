package com.github.cyberpartizan.notnullfork.processor

import com.google.devtools.ksp.symbol.KSClassDeclaration
import com.squareup.kotlinpoet.AnnotationSpec
import com.squareup.kotlinpoet.ClassName
import com.squareup.kotlinpoet.CodeBlock
import com.squareup.kotlinpoet.FileSpec
import com.squareup.kotlinpoet.FunSpec
import com.squareup.kotlinpoet.KModifier
import com.squareup.kotlinpoet.ParameterSpec
import com.squareup.kotlinpoet.ParameterizedTypeName.Companion.parameterizedBy
import com.squareup.kotlinpoet.PropertySpec
import com.squareup.kotlinpoet.TypeSpec
import com.squareup.kotlinpoet.joinToCode
import com.squareup.kotlinpoet.ksp.toClassName
import com.squareup.kotlinpoet.ksp.toTypeName

private val MIRROR = ClassName("com.github.cyberpartizan.notnullfork", "Mirror")
private val NOT_NULL = ClassName("jakarta.validation.constraints", "NotNull")

internal object MirrorGenerator {

    /**
     * Builds `{package}.generated.{RequestBody}Mirror`. Nested classes are joined with `_`
     * (`Outer.Inner` becomes `Outer_InnerMirror`); the runtime looks Mirrors up by this name.
     */
    fun generate(requestBody: KSClassDeclaration): FileSpec {
        val requestBodyName = requestBody.toClassName()
        val mirrorName = ClassName(
            listOf(requestBodyName.packageName, "generated").filter { it.isNotEmpty() }.joinToString("."),
            requestBodyName.simpleNames.joinToString("_") + "Mirror",
        )
        val fields = requestBody.primaryConstructor!!.parameters.map { it.name!!.asString() to it.type.toTypeName() }

        val constructor = FunSpec.constructorBuilder()
        val mirror = TypeSpec.classBuilder(mirrorName)
            .addKdoc("Mirror of [%T], generated by NotNullForK.", requestBodyName)
            .addSuperinterface(MIRROR.parameterizedBy(requestBodyName))
        for ((name, type) in fields) {
            val nullableType = type.copy(nullable = true)
            constructor.addParameter(ParameterSpec.builder(name, nullableType).defaultValue("null").build())
            mirror.addProperty(
                PropertySpec.builder(name, nullableType)
                    .initializer(name)
                    .addAnnotation(AnnotationSpec.builder(NOT_NULL).useSiteTarget(AnnotationSpec.UseSiteTarget.FIELD).build())
                    .build(),
            )
        }
        mirror.primaryConstructor(constructor.build())
        mirror.addFunction(
            FunSpec.builder("toRequestBody")
                .addModifiers(KModifier.OVERRIDE)
                .returns(requestBodyName)
                .addStatement(
                    "return %T(%L)",
                    requestBodyName,
                    fields.map { (name, _) -> CodeBlock.of("%N = %N!!", name, name) }.joinToCode(", "),
                )
                .build(),
        )

        return FileSpec.builder(mirrorName).addType(mirror.build()).build()
    }
}
